#!/usr/bin/env python3
"""Slice a frozen mesh with explicit settings and report verified artifacts."""
import argparse
import json
from pathlib import Path
import sys

from slicer_doctor import digest, run_process, validate_stl


def _same_value(a, b):
    a, b = str(a).strip().strip('"'), str(b).strip().strip('"')
    if a == b:
        return True
    try:
        return float(a) == float(b)
    except ValueError:
        return False


def _check_values(actual, expected):
    return [f'effective setting {key}: expected {value!r}, found {actual.get(key)!r}'
            for key, value in expected.items()
            if key not in actual or not _same_value(actual[key], value)]


def _gcode_statistics(path):
    # PrusaSlicer appends its estimates before the serialized config. Read a
    # bounded tail instead of copying potentially huge toolpaths into context.
    with Path(path).open('rb') as stream:
        stream.seek(0, 2)
        stream.seek(max(0, stream.tell() - 128 * 1024))
        tail = stream.read().decode('utf-8', errors='replace')
    return {line.split('=', 1)[0][2:].strip(): line.split('=', 1)[1].strip()
            for line in tail.splitlines()
            if '=' in line and line.startswith(('; estimated printing time', '; filament used'))}


def _gcode_version_header(path):
    with Path(path).open(encoding='utf-8-sig', errors='replace') as stream:
        for number, line in enumerate(stream):
            if number >= 30:
                break
            if line.lstrip().startswith(';') and 'generated by' in line.lower():
                return line.strip()
    return None


def _tool_hashes():
    result = {}
    for name in ['slice_project', 'validate_gcode', 'verify_3mf']:
        filename = __file__ if name == 'slice_project' else getattr(sys.modules.get(name), '__file__', None)
        path = Path(filename).resolve() if filename else None
        result[name] = {'path': str(path) if path else None,
                        'sha256': digest(path) if path and path.is_file() else None}
    return result


def slice_project(model, config, output_dir, command, expected=None,
                  bed=(250, 220, 270), margin=0, bead_radius=0,
                  startup_exceptions=None, timeout=300, center=None,
                  make_project=True):
    """Run a foreground CLI in a new/empty output directory.

    Inputs remain untouched and are hashed before/after. Configuration must be
    resolved (not an inheriting preset bundle). Effective G-code settings and
    supported toolpaths are checked before packaging a configured 3MF. Caller
    chooses the matching printer, material, bed and startup exception boxes.
    """
    from verify_3mf import inspect_3mf, package_project, load_config, config_from_gcode
    from validate_gcode import validate_gcode

    model, config, output_dir = (Path(p).resolve() for p in (model, config, output_dir))
    if not model.is_file() or not config.is_file():
        raise ValueError('frozen model and resolved config must exist')
    if not command or not isinstance(command, (list, tuple)) or not all(isinstance(a, str) for a in command):
        raise ValueError('command must be a nonempty argv list')
    if output_dir.exists() and (not output_dir.is_dir() or any(output_dir.iterdir())):
        raise ValueError('output directory must be new or empty; stale artifacts are not accepted')
    output_dir.mkdir(parents=True, exist_ok=True)
    report = {'status': 'fail', 'pass': False, 'issues': [], 'command': list(command),
              'input': str(model), 'input_sha256': digest(model),
              'config': str(config), 'config_sha256': digest(config), 'outputs': {},
              'tool_scripts': _tool_hashes()}
    try:
        requested = load_config(config)
        required = ['nozzle_diameter', 'layer_height', 'printer_settings_id', 'filament_type']
        if not requested or 'inherits' in requested or not all(requested.get(k) for k in required):
            raise ValueError('use a resolved INI declaring nozzle_diameter, layer_height, printer_settings_id and filament_type; preset inheritance is not resolved here')
        if model.suffix.lower() == '.3mf':
            initial = inspect_3mf(model)
            if initial.get('pass') is False or initial.get('status') in ['fail', 'unsupported']:
                raise ValueError('input 3MF failed inspection: ' + str(initial.get('issues', [])))
        elif model.suffix.lower() == '.stl':
            validate_stl(model)
        else:
            raise ValueError('supported frozen inputs are STL and 3MF')

        # Settings that could silently select a different hardware/material path.
        keys = ['printer_settings_id', 'printer_model', 'printer_variant',
                'filament_settings_id', 'filament_type', 'nozzle_diameter',
                'nozzle_high_flow', 'layer_height', 'perimeters', 'fill_density',
                'support_material', 'support_material_style']
        expectations = {k: requested[k] for k in keys if k in requested}
        for key, value in (expected or {}).items():
            if key in requested and not _same_value(requested[key], value):
                raise ValueError(f'configuration contradicts explicit expectation for {key}')
            expectations[key] = value
        report['expected_settings'] = expectations
        gcode = output_dir / 'slice.gcode'
        # An explicit resolved configuration must not inherit user GUI state or
        # modify the application's normal preference/preset directory.
        base = list(command) + ['--datadir', str(output_dir / 'slicer-state'), '--load', str(config)]
        if center is not None:
            if len(center) != 2:
                raise ValueError('center must contain X,Y')
            base += ['--center', ','.join(str(float(v)) for v in center)]
        process = run_process(base + ['--export-gcode', '--output', str(gcode), str(model)],
                              output_dir, output_dir / 'slice.log', timeout)
        report['slice_process'] = process
        if process['status'] != 'pass':
            raise ValueError('slicing process failed or timed out; inspect slice.log')
        if not gcode.is_file() or gcode.stat().st_size == 0:
            raise ValueError('slicer returned success without nonempty G-code; inspect launcher/path access')
        effective = config_from_gcode(gcode)
        if not effective:
            raise ValueError('G-code lacks parseable effective settings; do not infer presets from CLI arguments')
        report['effective_settings'] = {k: effective.get(k) for k in expectations}
        report['slicer_version_header'] = _gcode_version_header(gcode)
        report['statistics'] = _gcode_statistics(gcode)
        report['issues'].extend(_check_values(effective, expectations))
        if report['issues']:
            raise ValueError('effective settings mismatch')
        validation = validate_gcode(gcode, bed=bed, margin=margin,
                                    bead_radius=bead_radius,
                                    startup_exceptions=startup_exceptions or [])
        report['toolpaths'] = validation
        if not validation.get('pass', False):
            raise ValueError('toolpath validation failed or is unsupported')
        report['outputs']['gcode'] = {'path': str(gcode), 'sha256': digest(gcode)}
        # Keep the actual serialized config available even if project export fails.
        (output_dir / 'effective-config.json').write_text(json.dumps(effective, indent=2) + '\n')
        if make_project:
            geometry, project = output_dir / 'geometry.3mf', output_dir / 'project.3mf'
            export = run_process(base + ['--export-3mf', '--output', str(geometry), str(model)],
                                 output_dir, output_dir / 'export.log', timeout)
            report['export_process'] = export
            if export['status'] != 'pass' or not geometry.is_file() or geometry.stat().st_size == 0:
                raise ValueError('CLI project geometry export failed; inspect export.log')
            package_project(geometry, gcode, project)
            verification = inspect_3mf(project, require_config=True, expected=expectations)
            report['project_inspection'] = verification
            if not verification.get('pass', False):
                raise ValueError('packaged project failed geometry/config inspection')
            # Reopen in a separate isolated application state, without loading
            # the requested INI or applying placement again. This tests that
            # the delivered project itself supplies the effective settings.
            reopened_config, reopened_stl = output_dir / 'roundtrip.ini', output_dir / 'roundtrip.stl'
            reopen = run_process(list(command) + [
                '--datadir', str(output_dir / 'roundtrip-state'),
                '--save', str(reopened_config), '--export-stl',
                '--output', str(reopened_stl), str(project)],
                output_dir, output_dir / 'roundtrip.log', timeout)
            report['roundtrip_process'] = reopen
            if reopen['status'] != 'pass':
                raise ValueError('project reopen failed or timed out; inspect roundtrip.log')
            if any(not path.is_file() or path.stat().st_size == 0
                   for path in (reopened_config, reopened_stl)):
                raise ValueError('project reopen returned success without nonempty settings and STL outputs')
            report['roundtrip_geometry'] = validate_stl(reopened_stl)
            reopened = load_config(reopened_config)
            report['roundtrip_settings'] = {key: reopened.get(key) for key in expectations}
            mismatches = _check_values(reopened, expectations)
            if mismatches:
                report['issues'].extend('reopened project ' + item for item in mismatches)
                raise ValueError('reopened project settings mismatch')
            report['outputs']['project'] = {'path': str(project), 'sha256': digest(project)}
        report['status'], report['pass'] = 'pass', True
    except (OSError, ValueError, TypeError, KeyError) as exc:
        if str(exc) not in report['issues']:
            report['issues'].append(str(exc))
    finally:
        for path, key in [(model, 'input_sha256'), (config, 'config_sha256')]:
            try:
                unchanged = path.is_file() and digest(path) == report[key]
            except OSError:
                unchanged = False
            if not unchanged:
                report['issues'].append(f'frozen input changed during execution: {path}')
                report['status'], report['pass'] = 'fail', False
        (output_dir / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('model', type=Path)
    parser.add_argument('--config', required=True, type=Path, help='Resolved INI, not a preset bundle')
    parser.add_argument('--output-dir', required=True, type=Path, help='New or empty directory')
    parser.add_argument('--command-json', required=True, help='CLI argv JSON array, from slicer_doctor')
    parser.add_argument('--expect', action='append', default=[], metavar='KEY=VALUE')
    parser.add_argument('--bed', required=True, help='Width,depth,height in mm')
    parser.add_argument('--center', help='Optional X,Y plate center; placement is verified afterward')
    parser.add_argument('--margin', type=float, default=0)
    parser.add_argument('--bead-radius', type=float, default=0)
    parser.add_argument('--startup-exception', action='append', default=[],
                        help='Explicit pre-layer exception box xmin,xmax,ymin,ymax,zmin,zmax')
    parser.add_argument('--timeout', type=float, default=300)
    parser.add_argument('--no-project', action='store_true')
    args = parser.parse_args()
    try:
        expected = dict(item.split('=', 1) for item in args.expect)
        bed = tuple(float(x) for x in args.bed.split(','))
        if len(bed) != 3:
            raise ValueError('--bed requires width,depth,height')
        boxes = [tuple(float(x) for x in item.split(',')) for item in args.startup_exception]
        if any(len(box) != 6 for box in boxes):
            raise ValueError('startup exception requires six coordinates')
        result = slice_project(args.model, args.config, args.output_dir,
                               json.loads(args.command_json), expected, bed,
                               args.margin, args.bead_radius, boxes, args.timeout,
                               tuple(float(x) for x in args.center.split(',')) if args.center else None,
                               not args.no_project)
        print(json.dumps({'status': result['status'], 'issues': result['issues'],
                          'input_sha256': result['input_sha256'],
                          'statistics': result.get('statistics', {}),
                          'outputs': result['outputs'],
                          'report': str(Path(args.output_dir) / 'report.json')}, indent=2))
        return 0 if result['pass'] else 1
    except (OSError, ValueError, TypeError, ImportError) as exc:
        print(json.dumps({'status': 'fail', 'issues': [str(exc)]}))
        return 1


if __name__ == '__main__':
    sys.exit(main())
