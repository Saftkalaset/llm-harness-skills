def read_config(path):
    result = {}
    for line in Path(path).read_text().splitlines():
        line = line.removeprefix('; ').strip()
        if '=' in line:
            key, value = line.split('=', 1)
            if key.strip() != 'prusaslicer_config':
                result[key.strip()] = value.strip()
    return result


class SlicerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='slicer tests with spaces ')
        self.root = Path(self.temp.name)
        self.fake = self.root / 'fake cli.py'
        self.fake.write_text(FAKE_CLI)
        self.model = self.root / 'input model.stl'
        _write_probe(self.model)
        self.config = self.root / 'resolved settings.ini'
        self.config.write_text('nozzle_diameter = 0.4\nnozzle_high_flow = 0\nlayer_height = 0.2\nprinter_settings_id = Test printer\nfilament_type = PLA\n')
        self.verifier = types.ModuleType('verify_3mf')
        self.verifier.load_config = read_config
        self.verifier.config_from_gcode = read_config
        self.verifier.inspect_3mf = lambda *a, **kw: {'pass': True}
        self.verifier.package_project = lambda src, cfg, dst: Path(dst).write_bytes(b'configured project')
        self.validator = types.ModuleType('validate_gcode')
        self.validator.validate_gcode = lambda *a, **kw: {'status': 'pass', 'pass': True, 'issues': []}
        self.dependencies = patch.dict(sys.modules, {'verify_3mf': self.verifier, 'validate_gcode': self.validator})
        self.dependencies.start()

    def tearDown(self):
        self.dependencies.stop()
        self.temp.cleanup()

    def command(self, mode='good'):
        return [sys.executable, str(self.fake), mode]

    def sliced(self, mode='good', **kwargs):
        return slice_project(self.model, self.config, self.root / 'output', self.command(mode), **kwargs)

    def test_probe_verifies_nonempty_parseable_output_with_space_paths(self):
        result = probe_command(self.command(), self.root)
        self.assertEqual(result['status'], 'pass')
        self.assertEqual(result['output']['triangles'], 4)

    def test_exit_zero_without_output_is_failure(self):
        self.assertEqual(probe_command(self.command('missing'), self.root)['status'], 'fail')
        self.assertFalse(self.sliced('missing')['pass'])

    def test_malformed_probe_output_is_failure(self):
        result = probe_command(self.command('bad'), self.root)
        self.assertEqual(result['status'], 'fail')
        self.assertIn('unparseable', result['issues'][0])

    @unittest.skipUnless(sys.platform != 'win32', 'POSIX child process-group cleanup')
    def test_background_launcher_cannot_write_after_success(self):
        out = self.root / 'late artifact'
        result = run_process(self.command('background') + ['--output', str(out)],
                             self.root, self.root / 'background.log', timeout=2)
        self.assertEqual(result['status'], 'pass')
        time.sleep(.7)
        self.assertFalse(out.exists())

    def test_timeout_reports_failure(self):
        result = run_process(self.command('timeout'), self.root, self.root / 'timeout.log', .05)
        self.assertEqual(result['status'], 'timeout')

    def test_wrong_effective_high_flow_profile_rejected(self):
        result = self.sliced('wrong-profile')
        self.assertFalse(result['pass'])
        self.assertTrue(any('nozzle_high_flow' in issue for issue in result['issues']))

    def test_successful_slice_hashes_inputs_and_packages_output(self):
        result = self.sliced(expected={'nozzle_diameter': '.4'})
        self.assertTrue(result['pass'], result['issues'])
        self.assertEqual(len(result['input_sha256']), 64)
        self.assertTrue(Path(result['outputs']['project']['path']).is_file())
        self.assertEqual(result['effective_settings']['nozzle_high_flow'], '0')
        self.assertEqual(result['statistics']['filament used [g]'], '2.5')
        self.assertIn('PrusaSlicer 2.9.6',result['slicer_version_header'])
        self.assertEqual(len(result['tool_scripts']['slice_project']['sha256']),64)
        self.assertEqual(result['roundtrip_settings']['nozzle_high_flow'],'0')
        self.assertNotIn('--load',result['roundtrip_process']['command'])
        self.assertNotIn('--center',result['roundtrip_process']['command'])
        self.assertTrue((self.root / 'output' / 'report.json').exists())

    def test_wrong_reopened_project_settings_rejected(self):
        result=self.sliced('wrong-roundtrip')
        self.assertFalse(result['pass'])
        self.assertTrue(any('reopened project' in issue and 'nozzle_high_flow' in issue for issue in result['issues']))

    def test_missing_roundtrip_outputs_rejected(self):
        result=self.sliced('missing-roundtrip')
        self.assertFalse(result['pass'])
        self.assertTrue(any('nonempty settings and STL' in issue for issue in result['issues']))

    def test_malformed_roundtrip_stl_rejected(self):
        result=self.sliced('bad-roundtrip')
        self.assertFalse(result['pass'])
        self.assertNotIn('project',result['outputs'])

    def test_frozen_input_mutation_invalidates_result(self):
        result = self.sliced('mutate')
        self.assertFalse(result['pass'])
        self.assertTrue(any('frozen input changed' in issue for issue in result['issues']))

    def test_stale_artifact_directory_is_refused(self):
        output = self.root / 'output'
        output.mkdir(); (output / 'slice.gcode').write_text('old output')
        with self.assertRaisesRegex(ValueError, 'stale artifacts'):
            self.sliced('missing')

    def test_unresolved_preset_rejected(self):
        self.config.write_text('inherits = Default\nnozzle_diameter = .4\nlayer_height = .2\n')
        result = self.sliced()
        self.assertFalse(result['pass'])
        self.assertTrue(any('resolved INI' in issue for issue in result['issues']))

    def test_unsupported_toolpath_validation_never_passes(self):
        self.validator.validate_gcode = lambda *a, **kw: {'status': 'unsupported', 'pass': False}
        self.assertFalse(self.sliced()['pass'])

    def test_missing_material_declaration_is_not_a_resolved_process(self):
        self.config.write_text('nozzle_diameter = .4\nlayer_height = .2\nprinter_settings_id = Test\n')
        self.assertFalse(self.sliced()['pass'])

    def test_explicit_probe_cache_is_invalidated_on_command_change(self):
        cache = self.root / 'local cache.json'
        first = probe_command(self.command(), self.root, cache_path=cache)
        second = probe_command(self.command(), self.root, cache_path=cache)
        third = probe_command(self.command('missing'), self.root, cache_path=cache)
        self.assertEqual(first['status'], 'pass')
        self.assertTrue(second['cached'])
        self.assertEqual(third['status'], 'fail')

    def test_probe_cache_invalidated_when_wrapper_changes(self):
        cache = self.root / 'local cache.json'
        self.assertEqual(probe_command(self.command(), self.root, cache_path=cache)['status'], 'pass')
        self.fake.write_text(FAKE_CLI.replace("if mode=='missing':", "if mode=='good':"))
        self.assertEqual(probe_command(self.command(), self.root, cache_path=cache)['status'], 'fail')

    def test_flatpak_discovery_uses_direct_cli_and_preserves_branch(self):
        process = types.SimpleNamespace(stdout='com.prusa3d.PrusaSlicer\tbeta\tx86_64\ncom.prusa3d.PrusaSlicer\tstable\tx86_64\n')
        with patch('slicer_doctor.shutil.which', side_effect=lambda name: '/bin/flatpak' if name == 'flatpak' else None):
            with patch('slicer_doctor.subprocess.run', return_value=process):
                commands = discover_commands()
        self.assertEqual(commands[0]['branch'], 'stable')
        self.assertIn('--command=prusa-slicer', commands[0]['command'])
        self.assertTrue(commands[1]['command'][-1].endswith('/beta'))

    def test_malformed_explicit_command_is_refused_before_discovery(self):
        for command in ['[]', '"prusa-slicer"', '[""]', '[1]']:
            with self.subTest(command=command), patch.object(sys,'argv',['slicer_doctor.py','--command-json',command]):
                with contextlib.redirect_stdout(io.StringIO()) as output:
                    self.assertEqual(doctor_main(),1)
                self.assertEqual(json.loads(output.getvalue())['status'],'fail')


class ToolchainIntegrationTests(unittest.TestCase):
    def test_cli_effective_settings_and_project_packaging_with_real_helpers(self):
        from verify_3mf import inspect_3mf
        with tempfile.TemporaryDirectory(prefix='slicer integration ') as temp:
            root=Path(temp);fake=root/'fake cli.py';fake.write_text(FAKE_CLI)
            model=root/'input.stl';_write_probe(model)
            config=root/'settings.ini'
            config.write_text('nozzle_diameter = 0.4\nnozzle_high_flow = 0\nlayer_height = 0.2\nfilament_type = PLA\nprinter_settings_id = Test printer\n')
            result=slice_project(model,config,root/'output',[sys.executable,str(fake),'good'],
                                 expected={'nozzle_diameter':'.4'},bed=(30,30,30))
            self.assertTrue(result['pass'],result['issues'])
            project=inspect_3mf(result['outputs']['project']['path'],require_config=True)
            self.assertTrue(project['pass'],project['issues'])
            self.assertEqual(project['config']['nozzle_high_flow'],'0')
            self.assertEqual(result['toolpaths']['deposition_commands'],{'G1':1})
            self.assertTrue(all(len(tool['sha256'])==64 for tool in result['tool_scripts'].values()))


